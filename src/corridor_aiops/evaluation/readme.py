"""Render the README results block from results/*.json so no number is typed by hand.

The block between ``<!-- BEGIN GENERATED RESULTS -->`` and
``<!-- END GENERATED RESULTS -->`` in README.md is replaced; everything else is left
unchanged. Run ``python -m corridor_aiops.evaluation.readme`` after regenerating results.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

BEGIN = "<!-- BEGIN GENERATED RESULTS -->"
END = "<!-- END GENERATED RESULTS -->"


def _load(results: Path, name: str) -> dict[str, Any] | None:
    path = results / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _mean(block: dict[str, Any], key: str) -> float:
    return block["mean_std_across_training_seeds"][key]["mean"]


def _ms(block: dict[str, Any], key: str, scale: float = 1.0, digits: int = 3) -> str:
    entry = block["mean_std_across_training_seeds"][key]
    return f"{scale * entry['mean']:.{digits}f} ± {scale * entry['std']:.{digits}f}"


def _ci(interval: list[float], scale: float = 1.0, digits: int = 3) -> str:
    return f"[{scale * interval[0]:.{digits}f}, {scale * interval[1]:.{digits}f}]"


def _count(value: float) -> str:
    return f"{value:,.0f}"


def _series(items: list[str]) -> str:
    """Join names as an English series: "a", "a and b", "a, b, and c"."""
    if len(items) <= 2:
        return " and ".join(items)
    return ", ".join(items[:-1]) + ", and " + items[-1]


def render(results: Path) -> str:
    summary = _load(results, "benchmark_summary.json")
    if summary is None:
        raise FileNotFoundError("results/benchmark_summary.json is required")
    models = summary["models"]
    supervised = [n for n, b in models.items() if b["supervision_regime"] == "supervised"]
    lines = [
        BEGIN,
        "<!-- Generated by corridor_aiops.evaluation.readme from results/*.json; "
        "do not edit by hand. -->",
        "",
        f"### Headline results (official test split, {len(summary['protocol']['training_seeds'])}"
        " training seeds)",
        "",
        "| Regime | Model | F1 | AUROC | Val.-calibrated recall, 1% budget "
        "(realized test FAR) | Test ROC TPR at FAR 1% (retrospective) |",
        "|---|---|---|---|---|---|",
    ]
    for name, block in models.items():
        regime = "Supervised" if name in supervised else "Unsupervised / one-class"
        calibrated = _mean(block, "validation_calibrated_recall_at_far_1.0pct")
        realized = 100 * _mean(block, "validation_calibrated_realized_far_at_far_1.0pct")
        lines.append(
            f"| {regime} | {block['display_name']} | {_ms(block, 'f1_cyber_vs_benign')} | "
            f"{_ms(block, 'auroc')} | {calibrated:.3f} ({realized:.2f}%) | "
            f"{_mean(block, 'test_roc_tpr_at_far_1.0pct'):.3f} |"
        )
    lines += [
        "",
        "Values are mean ± sample standard deviation (or seed means) over training seeds. The "
        "primary operational metric is validation-calibrated recall with its realized test "
        "false-alarm rate; the test ROC TPR at 1% FPR places the threshold with test scores "
        "and is a retrospective curve diagnostic, not an achievable operating point.",
        "",
    ]
    bullets: list[str] = []

    capability = _load(results, "dataset_capability_matrix.json")
    if capability:
        totals: dict[str, int] = {}
        for archive in capability["datasets"]["veremi"]["official_ground_truth_cross_check"][
            "archives"
        ]:
            for split_counts in archive["record_outcomes_by_split"].values():
                for outcome, value in split_counts.items():
                    key = f"{archive['attack_category']}:{outcome}"
                    totals[key] = totals.get(key, 0) + value
        bullets.append(
            "**Official ground-truth consistency audit:** "
            f"{_count(totals.get('dataReplay:attacker_1_payload_differs', 0))} `dataReplay` "
            "attacker records are corroborated by state divergence, "
            f"{_count(totals.get('dosAttack:attacker_1_no_ground_truth_broadcast', 0))} "
            "`dosAttack` records by the absence of a ground-truth broadcast, and "
            f"{_count(totals.get('dosAttack:attacker_1_payload_matches', 0))} `dosAttack` "
            "records match their ground-truth broadcast in position and speed and remain "
            "uncorroborated (the audit compares only these fields). This is a consistency "
            "audit, not independent label validation."
        )

    boot = summary["uncertainty"]["sender_cluster_bootstrap"]
    deltas = boot["paired_differences_reference_minus_model"]
    worse = [
        models[n]["display_name"]
        for n, d in deltas.items()
        if d["delta_f1_cyber_vs_benign"]["ci_95pct"][1] < 0 and d["delta_auroc"]["ci_95pct"][1] < 0
    ]
    bullets.append(
        f"**Composite sender-cluster bootstrap** (first training seed; "
        f"{_count(boot['valid_replicates'])} of {_count(boot['requested_replicates'])} valid "
        f"replicates, {_count(boot['composite_clusters'])} clusters): "
        + (_series(worse) if worse else "no model")
        + " beat the Tabular Transformer with paired ΔF1 and ΔAUROC 95% intervals below zero."
    )
    sensitivity = _load(results, "seed_bootstrap_sensitivity.json")
    if sensitivity:
        bullets.append(
            "**Per-seed bootstrap sensitivity:** repeating the bootstrap for each training seed, "
            f"{sensitivity['ci_verdict_stable_count']} of {sensitivity['comparison_count']} "
            "paired verdicts are stable across seeds. Bootstrap replicates are resamples of one "
            "set of test senders, not independent experiments."
        )

    generalization = summary.get("generalization", {})
    loao = generalization.get("leave_one_attack_type_out", {})
    pairs = [
        (direction, name, _mean(block["models"][name], "auroc"))
        for direction, block in loao.items()
        if block.get("status") == "EVALUABLE"
        for name in supervised
    ]
    if pairs:
        below = sum(value < 0.5 for _, _, value in pairs)
        worst = min(pairs, key=lambda item: item[2])
        bullets.append(
            f"**Leave-one-attack-type-out:** supervised AUROC is below 0.5 in {below} of "
            f"{len(pairs)} model and direction pairs (lowest: {models[worst[1]]['display_name']} "
            f"{worst[2]:.3f}, `{worst[0]}`). The detectors are attack-specific, not attack-general."
        )

    diagnostics = _load(results, "loao_diagnostics.json")
    if diagnostics:
        audit = diagnostics["benign_overlap_audit"]["whole_archive_non_malicious"]
        bullets.append(
            "**Cross-archive benign overlap:** the two archives share "
            f"{_count(audit['message_sender_messageID_sendTime']['shared'])} identical "
            "non-malicious broadcasts, "
            f"{_count(audit['trajectory_window_L10']['shared'])} identical L = 10 windows, and "
            f"{_count(audit['bare_source_id']['shared'])} sender IDs."
        )
        dedup = diagnostics["loao_sender_disjoint"]["directions"]
        dedup_pairs = [
            (direction, name, _mean(block["models"][name], "auroc"))
            for direction, block in dedup.items()
            if block.get("status") == "EVALUABLE"
            for name in supervised
        ]
        if dedup_pairs:
            shared = [
                block["overlap_train_validation_vs_test_non_malicious"]
                for block in dedup.values()
                if block.get("status") == "EVALUABLE"
            ]
            bullets.append(
                "**Sender-disjoint deduplicated LOAO:** with "
                f"{max(s['bare_source_id']['shared'] for s in shared)} shared senders and "
                f"{max(s['message_sender_messageID_sendTime']['shared'] for s in shared)} shared "
                "non-malicious messages between training and test, supervised AUROC is below 0.5 "
                f"in {sum(v < 0.5 for _, _, v in dedup_pairs)} of {len(dedup_pairs)} pairs."
            )
        features = diagnostics["features"]["features"]
        reversed_names = [
            features[name]["label"] for name in diagnostics["features"]["reversed_features"]
        ]
        shifts = [block["benign_cross_archive_auroc_train"] for block in features.values()]
        bullets.append(
            "**Why LOAO fails:** "
            + _series([name[:1].upper() + name[1:].lower() if i == 0 else name.lower()
                       for i, name in enumerate(reversed_names)])
            + " mark attackers in opposite directions in the two attacks; non-malicious traffic "
            f"does not shift between archives (cross-archive AUROC {min(shifts):.3f} to "
            f"{max(shifts):.3f})."
        )
        procedures = diagnostics.get("threshold_procedures")
        if procedures:
            seeds = len(summary["protocol"]["training_seeds"])
            up = sum(
                procedures["models"][n]["paired_difference_vs_max_f1"]["youden_j"][
                    "seeds_with_higher_far"
                ]
                == seeds
                for n in supervised
            )
            bullets.append(
                "**Threshold procedures:** relative to validation max-F1, Youden's J raises the "
                f"test false-alarm rate for every seed in {up} of {len(supervised)} supervised "
                "detectors; FAR-budget quantile thresholds are compared in "
                "`results/results_threshold_procedures.tex`."
            )

        overlap = diagnostics.get("sender_overlap")
        if overlap:
            counts = overlap["counts_by_archive"].values()
            seen = sum(block["seen"]["senders"] for block in counts)
            unseen = sum(block["unseen"]["senders"] for block in counts)
            gaps = [
                overlap["models"][n]["seen"]["mean_std"]["auroc"]["mean"]
                - overlap["models"][n]["unseen"]["mean_std"]["auroc"]["mean"]
                for n in supervised
            ]
            bullets.append(
                f"**Seen versus unseen senders:** {seen} official test senders also occur in "
                f"the official training split and {unseen} do not, so official-split scores are "
                "not sender-independent; supervised AUROC on seen minus unseen senders ranges "
                f"from {min(gaps):+.3f} to {max(gaps):+.3f} "
                "(`results/results_sender_overlap.tex`)."
            )
        granularity = diagnostics.get("label_granularity")
        if granularity:
            official = granularity["contexts"]["official"]
            sender_level = [
                official["models"][n]["mean_std"]["sender_level_genuine_state|recall"]["mean"]
                for n in supervised
            ]
            bullets.append(
                "**Message-corroborated versus state-matching attacker records:** "
                f"{_count(official['group_counts']['message_corroborated'])} official test "
                "attacker records diverge from the ground truth in position or speed or have no "
                "ground-truth broadcast, and "
                f"{_count(official['group_counts']['sender_level_genuine_state'])} match it in "
                "position and speed; supervised recall on the state-matching group is "
                f"{min(sender_level):.3f} to {max(sender_level):.3f}, which cannot reflect "
                "falsified position or speed."
            )

    sensitivity_block = _load(results, "seed_bootstrap_sensitivity.json")
    if sensitivity_block and "effect_size_note" in sensitivity_block:
        rf = sensitivity_block["comparisons"].get("random_forest", {}).get("delta_auroc")
        if rf:
            effect = rf["effect_size"]
            dz = effect["standardized_effect_dz"]
            bullets.append(
                "**Effect sizes:** Tabular Transformer minus random forest AUROC averages "
                f"{effect['mean_paired_difference']:+.3f} over seeds (d_z "
                f"{'undefined' if dz is None else f'{dz:+.1f}'}); the fraction of bootstrap "
                "replicates favoring the Transformer averages "
                f"{effect['fraction_of_replicates_reference_better_mean']:.2f}. Percentile "
                "cluster-bootstrap intervals on imbalanced clustered data and "
                f"{len(summary['protocol']['training_seeds'])}-seed effect sizes are "
                "approximate."
            )

    for key, title in (
        ("sender_disjoint_holdout", "Sender-disjoint holdout"),
        ("chronological_holdout", "Chronological holdout"),
    ):
        block = generalization.get(key)
        if block and block.get("status") == "EVALUABLE":
            values = [_mean(block["models"][n], "auroc") for n in supervised]
            bullets.append(f"**{title}:** supervised AUROC {min(values):.3f} to {max(values):.3f}.")

    ablation = _load(results, "ablation_summary.json")
    if ablation and "one_class_window_length" in ablation["ablations"]:
        parts = []
        for result in ablation["ablations"]["one_class_window_length"]["models"].values():
            variant = result["variant_mean_std_across_training_seeds"]["auroc"]["mean"]
            full = result["full_mean_std_across_training_seeds"]["auroc"]["mean"]
            base = models[result["compared_with"]]["display_name"]
            parts.append(f"{base} {full:.3f} (L = 1) versus {variant:.3f} (L = 10)")
        bullets.append("**Matched L = 10 one-class controls:** AUROC " + "; ".join(parts) + ".")
    if ablation and "autoencoder_checkpoint_selection" in ablation["ablations"]:
        block = ablation["ablations"]["autoencoder_checkpoint_selection"]["models"]
        result = next(iter(block.values()))
        variant = result["variant_mean_std_across_training_seeds"]
        full = result["full_mean_std_across_training_seeds"]
        bullets.append(
            "**Label-free autoencoder checkpoint:** the main LSTM autoencoder trains on "
            "non-malicious sequences but selects its checkpoint by validation AUROC (attacker "
            "labels); selecting by benign validation reconstruction error instead gives AUROC "
            f"{variant['auroc']['mean']:.3f} versus {full['auroc']['mean']:.3f} and F1 "
            f"{variant['f1_cyber_vs_benign']['mean']:.3f} versus "
            f"{full['f1_cyber_vs_benign']['mean']:.3f}."
        )

    heldout = _load(results, "heldout_scenario.json")
    if heldout:
        rf = heldout["models"].get("random_forest")
        tt = heldout["models"].get("tabular_transformer")
        text = (
            f"**Held-out scenario `{heldout['heldout_scenario']}`** "
            f"({_count(heldout['class_counts']['test']['records'])} test messages, nothing fit "
            "or selected on it):"
        )
        if rf and tt:
            heldout_far = tt["confusion_mean_std_across_training_seeds"]["false_alarm_rate"]["mean"]
            main_far = _mean(models["tabular_transformer"], "false_alarm_rate_non_malicious")
            text += (
                f" random forest AUROC {_mean(rf, 'auroc'):.3f}, Tabular Transformer "
                f"{_mean(tt, 'auroc'):.3f}; Transformer FAR at its transferred threshold "
                f"{100 * heldout_far:.2f}% versus {100 * main_far:.2f}% on highway 2."
            )
        bullets.append(text + " Same attacks and simulator, so this is scenario transfer.")

    recalls = [
        block["emitter_ranking_and_simulated_latency"]["mean_std_across_training_seeds"].get(
            "attacker_emitter_recall_at_3", {"mean": 0.0}
        )["mean"]
        for block in models.values()
    ]
    bullets.append(
        f"**Sender ranking (negative result):** attacker-emitter recall at k = 3 is at most "
        f"{100 * max(recalls):.2f}%, so message-level detection does not provide reliable source "
        "localization."
    )

    reproduction = _load(results, "reproduction_audit.json")
    if reproduction and "numeric_values_compared" in reproduction:
        bullets.append(
            f"**Second-run reproduction:** {reproduction['determinism_status']}; "
            f"{_count(reproduction['numeric_values_with_nonzero_delta'])} of "
            f"{_count(reproduction['numeric_values_compared'])} numeric values differed "
            f"(maximum {reproduction['max_abs_numeric_delta']:.1e})."
        )
    clean = _load(results, "clean_checkout_audit.json")
    if clean:
        head = clean["headline_reproduction"]
        pytest_line = clean["linux_checks"]["pytest"]["summary_line"]
        bullets.append(
            f"**Clean checkout** (commit `{clean['commit'][:7]}`): "
            f"{_count(head['per_seed_values_compared'])} per-seed headline values, status "
            f"{head['status']}; Linux `ruff` {clean['linux_checks']['ruff']['status']}, "
            f"`pytest` {clean['linux_checks']['pytest']['status']} ({pytest_line})."
        )
    lines += [f"* {bullet}" for bullet in bullets]
    lines += ["", END]
    return "\n".join(lines)


def update_readme(readme: Path, results: Path) -> None:
    text = readme.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise ValueError("README.md lacks the generated-results markers")
    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    readme.write_text(text[:start] + render(results) + text[end:], encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--readme", type=Path, default=Path("README.md"))
    parser.add_argument("--results", type=Path, default=Path("results"))
    args = parser.parse_args()
    update_readme(args.readme, args.results)
    print(f"updated {args.readme}")


if __name__ == "__main__":
    main()
